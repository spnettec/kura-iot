package com.yofc.iot.docker.app;

import java.nio.charset.Charset;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import io.vertx.core.AbstractVerticle;
import io.vertx.core.Vertx;
import io.vertx.mqtt.MqttClient;
import io.vertx.mqtt.MqttClientOptions;

public class MqttOracle extends AbstractVerticle {

    private static final String MQTT_TOPIC = "/my_topic";
    private static final String BROKER_HOST = "localhost";
    private static final int BROKER_PORT = 1883;
    private static final Logger logger = LoggerFactory.getLogger(MqttOracle.class);

    @Override
    public void start() throws Exception {
        MqttClientOptions options = new MqttClientOptions().setKeepAliveTimeSeconds(2).setAutoKeepAlive(true)
                .setAutoGeneratedClientId(true);
        options.setReconnectAttempts(10).setReconnectInterval(2000);

        MqttClient client = MqttClient.create(Vertx.vertx(), options);

        client.publishHandler(publish -> {
            logger.info("Just received message on [" + publish.topicName() + "] payload ["
                    + publish.payload().toString(Charset.defaultCharset()) + "] with QoS [" + publish.qosLevel() + "]");
        });

        client.subscribeCompletionHandler(h -> {
            logger.info("Receive SUBACK from server with granted QoS :{} ", h.grantedQoSLevels());

        });

        client.connect(BROKER_PORT, BROKER_HOST, ch -> {
            if (ch.succeeded()) {
                logger.info("Connected to a server");
                client.subscribe(MQTT_TOPIC, 0);
            } else {
                logger.info("Failed to connect to a server");
                logger.error("error:{}", ch.cause());
            }
        });
        client.closeHandler(h -> {
            client.connect(BROKER_PORT, BROKER_HOST, ch -> {
                if (ch.succeeded()) {
                    logger.info("Connected to a server");
                    client.subscribe(MQTT_TOPIC, 0);
                } else {
                    logger.error("Failed to connect to a server");
                    logger.error("error:{}", ch.cause());
                }
            });
        });
    }
}
